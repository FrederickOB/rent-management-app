/** Shown for an unsubscribe link that does not resolve: unknown, or no longer kept. */
export default function UnsubscribeLinkNotValid() {
  return (
    <>
      <h1>This link is not valid or has expired</h1>
      <p>
        Links stop working after a while. Use the link in a newer email, or contact your landlord or
        property manager and ask them to stop sending you emails.
      </p>
    </>
  );
}
