/** Shown for a pay link that does not resolve: unknown, or no longer kept. */
export default function PayLinkNotValid() {
  return (
    <>
      <h1>This link is not valid or has expired</h1>
      <p>
        Links stop working after a while. Contact your landlord or property manager and ask them to
        send you a new link. Nothing has been charged.
      </p>
    </>
  );
}
