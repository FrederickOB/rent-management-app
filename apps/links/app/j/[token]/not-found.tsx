/** Shown for a job sheet link that does not resolve: unknown, or no longer kept. */
export default function JobSheetNotValid() {
  return (
    <>
      <h1>This link is not valid or has expired</h1>
      <p>
        Links stop working after a while. Contact the landlord or property manager who sent you the
        job and ask them to send you a new link.
      </p>
    </>
  );
}
